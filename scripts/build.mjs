import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

const result = await build({
  entryPoints: ['src/index.js'],
  outfile: 'index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  metafile: true,
  legalComments: 'eof',
  banner: { js: '// Generated by npm run build. Edit src/index.js or core.js, then rebuild.' },
  plugins: [{
    name: 'inline-harness-attribution-version',
    setup(builder) {
      builder.onLoad({ filter: /dsh-llm[\\/]lib[\\/]index\.js$/ }, async ({ path }) => {
        const source = await readFile(path, 'utf8');
        const manifest = JSON.parse(await readFile(join(dirname(path), '../package.json'), 'utf8'));
        const expression = 'createRequire(import.meta.url)("../package.json")';
        if (!source.includes(expression)) throw new Error('Harness attribution implementation changed; review the bundle adapter');
        return { contents: source.replace(expression, JSON.stringify({ version: manifest.version })), loader: 'js' };
      });
    },
  }],
});
const external = Object.values(result.metafile.outputs).flatMap(output => output.imports).filter(item => item.external && !item.path.startsWith('node:'));
if (external.length) throw new Error(`Unexpected runtime dependencies: ${external.map(item => item.path).join(', ')}`);
await mkdir('dist', { recursive: true });
await writeFile('dist/build-meta.json', JSON.stringify(result.metafile, null, 2));
const packages = new Map();
for (const output of Object.values(result.metafile.outputs)) {
  for (const [file, contribution] of Object.entries(output.inputs)) {
    if (!file.startsWith('node_modules/') || !contribution.bytesInOutput) continue;
    let dir = dirname(resolve(file));
    while (dir !== dirname(dir)) {
      try {
        const manifest = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
        if (manifest.name) { packages.set(manifest.name, { dir, manifest }); break; }
      } catch {}
      dir = dirname(dir);
    }
  }
}
const notices = [];
for (const [name, { dir, manifest }] of packages) {
  let license;
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENSE-MIT']) {
    try { license = await readFile(join(dir, file), 'utf8'); break; } catch {}
  }
  if (!license) throw new Error(`Missing bundled dependency license: ${name}`);
  notices.push(`${name}@${manifest.version}\n${license}`);
}
await writeFile('THIRD-PARTY-NOTICES.txt', notices.join('\n\n--------------------\n\n'));
